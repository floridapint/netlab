THEORY = r"""
# Протокол TCP
TCP (Transmission Control Protocol, RFC 9293) — надёжный транспорт поверх ненадёжного IP. Приложение видит **поток байтов**, который гарантированно доходит **полностью, без искажений и по порядку**.

## Что умеет TCP
- **Установка соединения** — трёхстороннее рукопожатие: SYN → SYN-ACK → ACK.
- **Нумерация байтов** — у каждого байта есть порядковый номер (sequence number).
- **Подтверждения (ACK)** — получатель сообщает, какой следующий байт он ждёт.
- **Повторная передача** — неподтверждённые данные отправляются снова: по таймауту (RTO) или после 3 дублирующих ACK (fast retransmit).
- **Упорядочивание** — сегменты собираются в правильном порядке, дубликаты отбрасываются.
- **Управление потоком** — окно (Window) не даёт «завалить» медленного получателя.
- **Контроль перегрузки** — алгоритмы Slow Start, CUBIC, BBR снижают скорость, если сеть перегружена.

## Трёхстороннее рукопожатие
```
Клиент                                       Сервер (LISTEN)
SYN_SENT     ---- SYN, seq=1000 ------------>
             <--- SYN-ACK, seq=5000, ack=1001   SYN_RCVD
ESTABLISHED  ---- ACK, seq=1001, ack=5001 -->   ESTABLISHED
```
- **ISN** (начальный номер) выбирается **случайно** — защита от подделки и путаницы со старыми соединениями.
- Флаг **SYN** «расходует» один номер, поэтому ack = ISN + 1.
- Почему три сообщения, а не два? Каждая сторона должна убедиться, что другая получила **её** начальный номер.

## Номера последовательности и подтверждения
- **seq** — номер первого байта данных в сегменте.
- **ack** — номер **следующего** байта, который ожидает получатель (значит, всё до него получено).
> Клиент отправил `seq=1001` и 100 байт (байты 1001…1100). Сервер отвечает `ack=1101`.
Подтверждения **кумулятивные**: `ack=1301` подтверждает сразу всё до байта 1300 включительно.

## Окно и скользящее окно
Поле **Window** — сколько байт получатель готов принять прямо сейчас. Отправитель может иметь «в полёте» столько неподтверждённых данных — это **скользящее окно**. Окно 0 означает «стоп, не успеваю». Чем больше окно, тем выше скорость на каналах с большой задержкой: пропускная способность ≤ окно / RTT.

## Флаги
|Флаг|Значение|
|---|---|
|SYN|Синхронизация номеров — начало соединения|
|ACK|Поле ack действительно (почти во всех сегментах)|
|FIN|Отправитель закончил передачу данных|
|RST|Немедленный сброс соединения (порт закрыт, ошибка)|
|PSH|Передать данные приложению немедленно|
|URG|Есть срочные данные (почти не используется)|

## Завершение соединения
Обычно 4 сегмента: **FIN → ACK, FIN → ACK**, потому что каждая сторона закрывает **своё** направление независимо (возможно «полузакрытое» соединение). Инициатор закрытия проходит через **TIME_WAIT** (2×MSL, обычно 30–120 с), чтобы опоздавшие сегменты не попали в новое соединение с теми же портами.
> **RST** обрывает соединение мгновенно и без подтверждений — например, при подключении к закрытому порту. Попробуйте в «Практике → Живые сокеты» кнопку «закрытый порт».

## Состояния TCP
`CLOSED`, `LISTEN`, `SYN_SENT`, `SYN_RCVD`, `ESTABLISHED`, `FIN_WAIT_1`, `FIN_WAIT_2`, `CLOSE_WAIT`, `LAST_ACK`, `TIME_WAIT`. Посмотреть их на своём компьютере: `netstat -an` или в PowerShell `Get-NetTCPConnection`.

## TCP — поток, а не сообщения
TCP не сохраняет границы `send()`. Три вызова `send("раз")`, `send("два")`, `send("три")` могут прийти одним `recv()` как `"раздватри"` — или кусками. Протоколы поверх TCP сами отделяют сообщения: длиной (Content-Length в HTTP), разделителем (`\r\n`) или кадрированием (HTTP/2).
> Проверьте вживую: «Практика → Живые сокеты», включите задержку чтения и нажмите «3 сообщения подряд».

## TCP в Python
```
import socket
srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
srv.bind(("127.0.0.1", 9000)); srv.listen()     # LISTEN
conn, addr = srv.accept()                        # ждём рукопожатия
data = conn.recv(4096)                           # читаем из потока
conn.sendall(data)

cli = socket.create_connection(("127.0.0.1", 9000))  # SYN → SYN-ACK → ACK
cli.sendall(b"hello")
cli.close()                                           # FIN
```

## TCP или UDP?
|Критерий|TCP|UDP|
|---|---|---|
|Соединение|Да (рукопожатие)|Нет|
|Надёжность|Гарантирована|Нет|
|Порядок|Сохраняется|Не гарантирован|
|Границы сообщений|Нет (поток)|Да (датаграммы)|
|Заголовок|20–60 байт|8 байт|
|Старт|1 RTT на рукопожатие|Мгновенно|
|Примеры|HTTP/1.1 и 2, SSH, почта, БД|DNS, VoIP, игры, QUIC|
"""

CLIENT = (N_("Клиент"), "192.168.1.10 : 51000", T.ACCENT)
SERVER = (N_("Сервер"), "93.184.216.34 : 443", T.GOOD)


def B(n):
    """«{n} байт» на текущем языке."""
    return _("{n} байт").format(n=n)


class HandshakeScenario(SequenceScenario):
    title = N_("Рукопожатие")
    intro = N_("Прежде чем передавать данные, TCP устанавливает соединение: стороны обмениваются **начальными номерами "
               "последовательности**. Сервер уже вызвал `listen()` и находится в состоянии `LISTEN`.")
    actors = [CLIENT, SERVER]
    initial_states = {0: "CLOSED", 1: "LISTEN"}
    dy = 46
    gap = 26

    def steps(self):
        return [
            self.msg(0, 1, "SYN  seq=1000", _("Клиент выбирает **случайный** начальный номер (ISN) = 1000 и отправляет "
                     "сегмент с флагом **SYN** («давай синхронизируем номера»). Клиент переходит в `SYN_SENT`."),
                     "SYN", T.ACCENT, states={0: "SYN_SENT"}, chip="SYN"),
            self.msg(1, 0, "SYN-ACK  seq=5000, ack=1001", _("Сервер выбирает свой ISN = 5000 и отвечает **SYN-ACK**: "
                     "«согласен, мой номер 5000; твой SYN получен, жду байт 1001». SYN занял один номер — поэтому "
                     "ack = 1000 + 1."), "SYN-ACK", T.WARN, states={1: "SYN_RCVD"}, chip="SYN-ACK"),
            self.msg(0, 1, "ACK  seq=1001, ack=5001", _("Клиент подтверждает SYN сервера: ack = 5000 + 1. Теперь обе "
                     "стороны знают номера друг друга — соединение **установлено**."), "ACK", T.GOOD,
                     states={0: "ESTABLISHED", 1: "ESTABLISHED"}, chip="ACK"),
            Step(_("**Почему именно три сообщения?** Каждая сторона должна отправить свой ISN **и** получить "
                   "подтверждение. SYN-ACK совмещает ответ сервера и его собственный SYN, поэтому хватает трёх. Цена — "
                   "**1 RTT** до начала передачи данных. Если на SYN никто не ответил — клиент повторит его через 1, 2, "
                   "4… секунды."), None, _("Итог")),
        ]


class DataScenario(SequenceScenario):
    title = N_("Передача данных")
    intro = N_("Соединение установлено (ISN клиента = 1000, сервера = 5000). Посмотрим, как работают номера **seq** и "
               "**ack**.")
    actors = [CLIENT, SERVER]
    initial_states = {0: "ESTABLISHED", 1: "ESTABLISHED"}
    dy = 26
    gap = 16

    def steps(self):
        return [
            self.msg(0, 1, f"seq=1001, {B(100)}", _("Клиент отправляет 100 байт данных. **seq=1001** — номер первого "
                     "байта в сегменте; он несёт байты 1001…1100."), _("Данные"), T.ACCENT, chip=B(100)),
            self.msg(1, 0, "ACK  ack=1101", _("Сервер подтверждает: «получил всё до 1100, жду **1101**»."), "ACK", T.GOOD,
                     chip="ACK"),
            self.msg(0, 1, f"seq=1101, {B(100)}", _("Клиент не обязан ждать ACK на каждый сегмент — окно позволяет "
                     "отправить несколько подряд."), _("Окно"), T.ACCENT, chip=B(100)),
            self.msg(0, 1, f"seq=1201, {B(100)}", _("Второй сегмент сразу за первым: байты 1201…1300."), _("Окно"),
                     T.ACCENT, chip=B(100)),
            self.msg(1, 0, _("ACK  ack=1301 (кумулятивный)"), _("Один ACK подтверждает **оба** сегмента: ack=1301 значит "
                     "«всё до 1300 включительно получено». Это **кумулятивное** подтверждение."), "ACK", T.GOOD, chip="ACK"),
            self.msg(1, 0, f"seq=5001, ack=1301, {B(50)}", _("Сервер отправляет ответ (50 байт), заодно подтверждая "
                     "данные клиента в том же сегменте (piggybacking)."), _("Ответ"), T.WARN, chip=B(50)),
            self.msg(0, 1, "ACK  ack=5051", _("Клиент подтверждает ответ: 5001 + 50 = **5051**. Номера каждой стороны "
                     "растут независимо."), "ACK", T.GOOD, chip="ACK"),
        ]


class LossScenario(SequenceScenario):
    title = N_("Потеря и повтор")
    intro = N_("Что будет, если сегмент потеряется в сети? TCP заметит «дыру» по номерам и отправит данные заново.")
    actors = [CLIENT, SERVER]
    initial_states = {0: "ESTABLISHED", 1: "ESTABLISHED"}
    dy = 24
    gap = 14

    def steps(self):
        return [
            self.msg(0, 1, f"seq=1001, {B(100)}", _("Первый сегмент доходит."), _("Сегмент 1"), T.ACCENT, chip="1001"),
            self.msg(1, 0, "ACK 1101", _("Сервер подтверждает: жду 1101."), "ACK", T.GOOD, chip="ACK"),
            self.msg(0, 1, f"seq=1101, {B(100)}", _("Второй сегмент **теряется** по дороге."), _("Потеря"), T.ACCENT,
                     lost=True, chip="1101"),
            self.msg(0, 1, f"seq=1201, {B(100)}", _("Третий сегмент доходит. Сервер кладёт его в буфер, но отдать "
                     "приложению не может — перед ним «дыра» (байты 1101…1200)."), _("Сегмент 3"), T.ACCENT, chip="1201"),
            self.msg(1, 0, _("ACK 1101 (дубликат)"), _("Сервер снова отправляет **ACK 1101**: «я всё ещё жду байт 1101». "
                     "Это **дублирующий ACK**."), _("Дубль ACK"), T.WARN, chip="ACK"),
            self.note(0, _("⏱ RTO истёк / 3 дубля ACK → повтор"), _("Клиент понимает, что сегмент 1101 потерян: либо "
                      "истёк таймер повторной передачи (**RTO**), либо пришло три дублирующих ACK (**fast retransmit**)."),
                      _("Обнаружение"), advance=26),
            self.msg(0, 1, f"seq=1101, {B(100)} " + _("(повтор)"), _("Клиент **повторно** отправляет потерянный сегмент."),
                     _("Повтор"), T.PINK, chip="1101"),
            self.msg(1, 0, "ACK 1301", _("Дыра закрыта, а сегмент 1201 уже лежит в буфере — сервер подтверждает **всё "
                     "сразу**: ack=1301. Приложение получает байты строго по порядку. (С опцией **SACK** сервер мог бы "
                     "заранее сообщить, какие куски у него уже есть.)"), "ACK", T.GOOD, chip="ACK"),
        ]


class CloseScenario(SequenceScenario):
    title = N_("Закрытие")
    intro = N_("Соединение закрывается **в каждую сторону отдельно**. Обычно это 4 сегмента. Инициатор — клиент "
               "(вызвал `close()`).")
    actors = [CLIENT, SERVER]
    initial_states = {0: "ESTABLISHED", 1: "ESTABLISHED"}
    dy = 34
    gap = 20

    def steps(self):
        return [
            self.msg(0, 1, "FIN  seq=2000", _("Клиент закончил передачу и отправляет **FIN**: «я больше ничего не "
                     "пошлю». Состояние `FIN_WAIT_1`."), "FIN", T.WARN, states={0: "FIN_WAIT_1"}, chip="FIN"),
            self.msg(1, 0, "ACK  ack=2001", _("Сервер подтверждает FIN (FIN тоже занимает 1 номер). Сервер в "
                     "`CLOSE_WAIT`: его приложение получило «конец файла» (recv вернул 0 байт). Клиент ждёт в "
                     "`FIN_WAIT_2`."), "ACK", T.GOOD, states={1: "CLOSE_WAIT", 0: "FIN_WAIT_2"}, chip="ACK"),
            self.note(1, _("сервер дописывает свои данные…"), _("Соединение **полузакрыто**: клиент → сервер закрыто, а "
                      "сервер ещё может отправлять данные клиенту."), _("Полузакрыто"), advance=28),
            self.msg(1, 0, "FIN  seq=7000", _("Сервер тоже закрывает своё направление — **FIN**. Состояние `LAST_ACK`."),
                     "FIN", T.WARN, states={1: "LAST_ACK"}, chip="FIN"),
            self.msg(0, 1, "ACK  ack=7001", _("Клиент подтверждает. Сервер сразу переходит в `CLOSED`, а клиент — в "
                     "**`TIME_WAIT`**."), "ACK", T.GOOD, states={0: "TIME_WAIT", 1: "CLOSED"}, chip="ACK"),
            self.note(0, _("⏱ 2×MSL → CLOSED"), _("**TIME_WAIT** длится 2×MSL (30–120 с): если последний ACK потерялся, "
                      "сервер повторит FIN, и клиент сможет ответить. А ещё это защищает новое соединение с теми же "
                      "портами от опоздавших сегментов. Альтернатива — **RST**: мгновенный обрыв без любезностей."),
                      "TIME_WAIT"),
        ]


