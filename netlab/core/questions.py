def get_questions(topic: str) -> list:
    """Вопросы темы на текущем языке интерфейса."""
    return content("QUESTIONS", topic, QUESTIONS[topic])


def all_questions():
    out = []
    for topic in QUESTIONS:
        for q in get_questions(topic):
            out.append({**q, "topic": topic})
    return out
